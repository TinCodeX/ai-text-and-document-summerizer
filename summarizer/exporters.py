"""
AI Document & Text Summarizer - Multi-Format Exporters
======================================================
Serializes validated SummaryResult models into clean, structured Markdown,
JSON, and Plain-Text representations within a timestamped output directory.
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from typing import Optional, Union

try:
    from .schema import SummaryResult
except (ImportError, ValueError):
    from schema import SummaryResult


def _slugify_title(title: str, max_chars: int = 40) -> str:
    """Converts a title string into a safe, clean filesystem slug."""
    slug = re.sub(r"[^\w\s-]", "", title.strip()).strip()
    slug = re.sub(r"[\s_-]+", "_", slug).lower()
    return slug[:max_chars].rstrip("_") or "summary"


def _format_markdown(result: SummaryResult) -> str:
    """Formats SummaryResult into clean GitHub-flavored Markdown."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        f"# {result.title}",
        "",
        "> **Executive Summary**",
        f"> {result.executive_summary}",
        "",
        "## Key Takeaways",
    ]

    for item in result.key_takeaways:
        lines.append(f"- {item}")

    if result.action_items:
        lines.extend(["", "## Action Items & Next Steps"])
        for item in result.action_items:
            lines.append(f"- [ ] {item}")

    lines.extend([
        "",
        "---",
        f"*Generated by AI Document & Text Summarizer on {now_str}*",
        "",
        f"**Style:** `{result.format_applied}` | "
        f"**Tone:** `{result.sentiment_or_tone}` | "
        f"**Original Word Count:** `{result.word_count_original}` words",
        "",
    ])

    return "\n".join(lines)


def _format_plain_text(result: SummaryResult) -> str:
    """Formats SummaryResult into clean, readable ASCII plain text."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    divider = "=" * 70
    subdivider = "-" * 70

    lines = [
        divider,
        result.title.upper(),
        divider,
        "",
        "EXECUTIVE SUMMARY:",
        result.executive_summary,
        "",
        subdivider,
        "KEY TAKEAWAYS:",
    ]

    for i, item in enumerate(result.key_takeaways, 1):
        lines.append(f"  {i}. {item}")

    if result.action_items:
        lines.extend(["", subdivider, "ACTION ITEMS:"])
        for item in result.action_items:
            lines.append(f"  [ ] {item}")

    lines.extend([
        "",
        divider,
        f"Metadata: Style={result.format_applied} | Tone={result.sentiment_or_tone} | Words={result.word_count_original}",
        f"Timestamp: {now_str}",
        divider,
        "",
    ])

    return "\n".join(lines)


def export_summary(
    result: SummaryResult,
    output_dir: Union[str, Path] = "output",
    file_prefix: Optional[str] = None,
    formats: Optional[list[str]] = None,
) -> dict[str, Path]:
    """
    Exports SummaryResult to target formats (.md, .json, .txt).

    Args:
        result: Validated SummaryResult instance.
        output_dir: Destination folder path (auto-created if missing).
        file_prefix: Optional custom filename prefix.
        formats: Target formats list (e.g. ['md', 'json', 'txt']). Default: ['md', 'json'].

    Returns:
        Dictionary mapping format extension to written Path object.
    """
    target_dir = Path(output_dir).resolve()
    target_dir.mkdir(parents=True, exist_ok=True)

    if formats is None:
        selected_formats = ["md", "json"]
    else:
        # Normalize format strings (e.g. ".md" -> "md", "ALL" -> all formats)
        cleaned = [f.strip().lstrip(".").lower() for f in formats if f.strip()]
        if "all" in cleaned:
            selected_formats = ["md", "json", "txt"]
        else:
            selected_formats = [f for f in cleaned if f in {"md", "json", "txt"}]

    if not selected_formats:
        selected_formats = ["md", "json"]

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    slug = _slugify_title(result.title)

    if file_prefix and file_prefix.strip():
        clean_pfx = re.sub(r"[^\w-]", "", file_prefix.strip()).rstrip("_")
        base_name = f"{timestamp}_{clean_pfx}_{slug}"
    else:
        base_name = f"{timestamp}_{slug}"

    written_paths: dict[str, Path] = {}

    # 1. JSON Export
    if "json" in selected_formats:
        json_path = target_dir / f"{base_name}.json"
        json_path.write_text(result.model_dump_json(indent=2), encoding="utf-8")
        written_paths["json"] = json_path

    # 2. Markdown Export
    if "md" in selected_formats:
        md_path = target_dir / f"{base_name}.md"
        md_path.write_text(_format_markdown(result), encoding="utf-8")
        written_paths["md"] = md_path

    # 3. Plain Text Export
    if "txt" in selected_formats:
        txt_path = target_dir / f"{base_name}.txt"
        txt_path.write_text(_format_plain_text(result), encoding="utf-8")
        written_paths["txt"] = txt_path

    return written_paths
